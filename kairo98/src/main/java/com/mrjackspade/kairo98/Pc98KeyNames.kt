package com.mrjackspade.kairo98

/** Labels follow the pinned 21/W keystat.tbl scan-code table. */
object Pc98KeyNames {
    fun label(scan: Int): String = when (scan) {
        0x00 -> "Esc"
        in 0x01..0x09 -> "$scan"
        0x0a -> "0"
        0x0b -> "-"
        0x0c -> "^"
        0x0d -> "Backslash"
        0x0e -> "Backspace"
        0x0f -> "Tab"
        in 0x10..0x19 -> "QWERTYUIOP"[scan - 0x10].toString()
        0x1a -> "@"
        0x1b -> "["
        0x1c -> "Enter"
        in 0x1d..0x25 -> "ASDFGHJKL"[scan - 0x1d].toString()
        0x26 -> ";"
        0x27 -> ":"
        0x28 -> "]"
        in 0x29..0x2f -> "ZXCVBNM"[scan - 0x29].toString()
        0x30 -> ","
        0x31 -> "."
        0x32 -> "/"
        0x33 -> "_"
        0x34 -> "Space"
        0x35 -> "Xfer"
        0x36 -> "Roll up"
        0x37 -> "Roll down"
        0x38 -> "Insert"
        0x39 -> "Delete"
        0x3a -> "Up"
        0x3b -> "Left"
        0x3c -> "Right"
        0x3d -> "Down"
        0x3e -> "Home"
        0x3f -> "Help/End"
        0x40 -> "Numpad -"
        0x41 -> "Numpad /"
        in 0x42..0x44 -> "Numpad ${scan - 0x3b}"
        0x45 -> "Numpad *"
        in 0x46..0x48 -> "Numpad ${scan - 0x42}"
        0x49 -> "Numpad +"
        in 0x4a..0x4c -> "Numpad ${scan - 0x49}"
        0x4d -> "Numpad ="
        0x4e -> "Numpad 0"
        0x4f -> "Numpad ,"
        0x50 -> "Numpad ."
        0x51 -> "Nfer"
        in 0x52..0x56 -> "VF${scan - 0x51}"
        0x60 -> "Stop"
        0x61 -> "Copy"
        in 0x62..0x6b -> "F${scan - 0x61}"
        0x70 -> "Shift"
        0x71 -> "Caps"
        0x72 -> "Kana"
        0x73 -> "Graph/Alt"
        0x74 -> "Ctrl"
        0x77 -> "Left Win"
        0x78 -> "Right Win"
        0x79 -> "App"
        0x7d -> "Right Shift"
        else -> "Scan 0x${scan.toString(16).padStart(2, '0')}"
    }
}
